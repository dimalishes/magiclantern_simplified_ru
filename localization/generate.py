#!/usr/bin/env python3
"""Generate Russian lookup table and extend RBF fonts without changing old glyphs."""
import json
import re
import struct
from pathlib import Path
from cyrillic_font import make_cyrillic

ROOT = Path(__file__).resolve().parents[1]
LETTERS = ''.join(chr(c) for c in range(0x410, 0x450)) + 'Ёё'
CODES = {c: 160 + i for i, c in enumerate(LETTERS)}
HEADER = struct.Struct('<2I64s11i')

def encode(s):
    return bytes(ord(c) if ord(c) < 128 or ord(c) in (0x84, 0x86) else CODES[c] for c in s)

def catalog(filename='ru.tsv'):
    result = {}
    for line in (ROOT/'localization'/filename).read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        en, ru = line.split('\t')
        # Keep TSV/review files one record per line; decode explicit C-style
        # line endings and escaped backslashes for complete notification text.
        escapes = {'n': '\n', 'r': '\r', '\\': '\\', 'x84': chr(0x84), 'x86': chr(0x86)}
        en = re.sub(r'\\(x84|x86|[nr\\])', lambda m: escapes[m[1]], en)
        ru = re.sub(r'\\(x84|x86|[nr\\])', lambda m: escapes[m[1]], ru)
        assert en not in result, f'Duplicate key: {en}'
        assert all(ord(c)<128 or ord(c) in (0x84,0x86) for c in en), en
        assert len(encode(ru)) < 128, en
        result[en] = ru
    return result

def c_string(b):
    # Fixed-width octal escapes cannot absorb following ASCII digits.
    return '"' + ''.join(chr(c) if 32 <= c < 127 and c not in (34,92) else f'\\{c:03o}' for c in b) + '"'

def main():
    entries = catalog()
    # These four approved templates are used by the bounded config composer.
    # Only %s substitutions are supported; never admit another printf opcode.
    for key in ('Only the current preset: %s', 'Config: %s',
                'Restart to load the config for %s mode.',
                'Camera was started in %s; restart to load the config for %s.'):
        value = entries[key]
        assert value.count('%s') == key.count('%s') and '%' not in value.replace('%s', ''), key
    # Bounded choice composer uses only these trusted printf signatures.
    for key in ('%s, over %d%%', '%s, under %d%%', '%s, %d..%d%%', 'ON,%d.%d,%s%s'):
        assert re.findall(r'%[%sd]', entries[key]) == re.findall(r'%[%sd]', key), key
        assert '%' not in re.sub(r'%[%sd]', '', entries[key]), key
    out = ['/* Generated by localization/generate.py. Do not edit. */',
           'static const struct { const char *en; const char *ru; } menu_ru_catalog[] = {']
    out += [f'    {{{c_string(en.encode("latin1"))}, {c_string(encode(ru))}}},' for en,ru in sorted(entries.items())]
    out += ['};', '', '''static const char *menu_ru_lookup(const char *text)
{
    unsigned lo = 0, hi = sizeof(menu_ru_catalog) / sizeof(menu_ru_catalog[0]);
    while (lo < hi)
    {
        unsigned mid = lo + (hi - lo) / 2;
        int cmp = strcmp(text, menu_ru_catalog[mid].en);
        if (!cmp) return menu_ru_catalog[mid].ru;
        if (cmp < 0) hi = mid;
        else lo = mid + 1;
    }
    return text;
}
''']
    summaries = catalog('module-summary-ru.tsv')
    out += ['static const struct { const char *en; const char *ru; } module_ru_summaries[] = {']
    out += [f'    {{{c_string(en.encode("latin1"))}, {c_string(encode(ru))}}},' for en,ru in sorted(summaries.items())]
    out += ['};', '''static inline const char *module_ru_summary_lookup(const char *text)
{
    for (unsigned i = 0; i < sizeof(module_ru_summaries) / sizeof(module_ru_summaries[0]); i++)
        if (!strcmp(text, module_ru_summaries[i].en)) return module_ru_summaries[i].ru;
    return text;
}
''']
    names = catalog('module-names-ru.tsv')
    out += ['static const struct { const char *en; const char *ru; } module_ru_names[] = {']
    out += [f'    {{{c_string(en.encode("latin1"))}, {c_string(encode(ru))}}},' for en,ru in sorted(names.items())]
    out += ['};', '''static inline const char *module_ru_name_lookup(const char *text)
{
    for (unsigned i = 0; i < sizeof(module_ru_names) / sizeof(module_ru_names[0]); i++)
        if (!strcmp(text, module_ru_names[i].en)) return module_ru_names[i].ru;
    return text;
}
''']
    from final_patterns import generate_patterns
    generate_patterns(entries)
    (ROOT/'src/menu_ru_data.h').write_text('\n'.join(out))
    for path in sorted((ROOT/'data/fonts').glob('*.rbf')):
        data = path.read_bytes()
        h = list(HEADER.unpack_from(data))
        charsize, height, first, last, woff, coff = h[3], h[5], h[7], h[8], h[10], h[11]
        # Always preserve the original 32..159 glyphs, including ML icons.
        assert first == 32 and last in (159,225)
        old_count = 160-first
        widths = bytearray(data[woff:woff+old_count])
        glyphs = bytearray(data[coff:coff+old_count*charsize])
        stride = charsize // height
        assert stride*height == charsize
        cyr_widths, cyr_glyphs, metrics = make_cyrillic(data, h, LETTERS, path.name)
        widths.extend(cyr_widths)
        glyphs.extend(cyr_glyphs)
        h[8] = 225
        h[10] = HEADER.size
        h[11] = HEADER.size+len(widths)
        path.write_bytes(HEADER.pack(*h)+widths+glyphs)
        print(f'{path.name}: Latin-aligned {metrics}')
    print(f'Generated {len(entries)} translations, {len(LETTERS)} Cyrillic glyphs in each of 6 fonts.')
    print(f'Generated {len(summaries)} scoped module summaries and {len(names)} display names.')

if __name__ == '__main__':
    main()
